#!/usr/bin/env python3
"""Freeze emitted backend body and bootstrap callback bytes for the native gate."""
from pathlib import Path
import struct
import sys

body, stub, output = map(Path, sys.argv[1:])
lines = ["/* Generated by callback-emit.factor and the bootstrap callback emitter. */"]
for name, code, reloc in (
    ("body", body / "m88k-callback-body.bin", body / "m88k-callback-body-relocations.bin"),
    ("stub", stub / "boot-callback.bin", stub / "boot-callback-relocations.bin"),
):
    raw = code.read_bytes()
    if name == "body":
        loads = [word & 0xffff for (word,) in struct.iter_unpack(">I", raw)
                 if word >> 16 == 0x1690]
        if loads != [16, 16]:
            raise ValueError("callback body must use target32 context.callstack_save at16")
    data = ",".join(f"0x{x:02x}" for x in raw)
    lines.append(f"static const unsigned char callback_{name}[] = {{{data}}};")
    fixups = []
    words = [word for (word,) in struct.iter_unpack(">I", reloc.read_bytes())]
    expected = [0, 0, 0] if name == "body" else [9, 15, 12, 13, 1]
    if [word >> 28 for word in words] != expected:
        raise ValueError("unexpected callback relocation order")
    for word in words:
        if (word >> 24) & 15 != 14:
            raise ValueError("callback requires native0 pair relocations")
        fixups.append(f"{{{word >> 28},{word & 0xffffff}}}")
    lines.append(f"static const unsigned callback_{name}_fixups[][2] = {{"
                 + ",".join(fixups) + "};")
output.write_text("\n".join(lines) + "\n")
values = ",".join(f"0x{x:02x}" for x in (body / "m88k-callback-map.bin").read_bytes())
with output.open("a") as stream:
    stream.write(f"static const unsigned char callback_map[] = {{{values}}};\n")

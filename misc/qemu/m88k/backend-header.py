#!/usr/bin/env python3
"""Pack optimizer-emit.factor and cfg-emit.factor outputs for the native gate."""
import argparse
from pathlib import Path
import struct


def make_header(directory):
    lines = ["/* Generated by optimizer-emit.factor and cfg-emit.factor. */"]
    for path in sorted(directory.glob("m88k-*.bin")):
        if path.name.endswith("-relocations.bin"):
            continue
        name = path.stem.replace("-", "_")
        data = ",".join(f"0x{byte:02x}" for byte in path.read_bytes())
        lines.append(f"static const unsigned char {name}[] = {{{data}}};")
    literals = [int(value) for value in
                (directory / "m88k-cfg-float-literals.txt").read_text().split(",")]
    relocations = (directory / "m88k-cfg-float-relocations.bin").read_bytes()
    if len(relocations) != 4 * len(literals):
        raise ValueError("floating literal and relocation counts differ")
    fixups = []
    for (word,), target in zip(struct.iter_unpack(">I", relocations), literals):
        # RT_LITERAL, RC_NATIVE_0; the literal encodes a negated code offset.
        if word >> 28 != 4 or (word >> 24) & 15 != 14 or target >= 0:
            raise ValueError("unexpected floating literal relocation")
        fixups.append(f"{{{word & 0xffffff},{-target}}}")
    lines.append("static const unsigned m88k_cfg_float_fixups[][2] = {"
                 + ",".join(fixups) + "};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("emission_directory", type=Path)
    parser.add_argument("header", type=Path)
    arguments = parser.parse_args()
    arguments.header.write_text(make_header(arguments.emission_directory))

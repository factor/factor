#!/usr/bin/env python3
"""Pack nested-frame-emit.factor outputs for the native audit."""
from pathlib import Path
import sys

directory = Path(sys.argv[1])
lines = ["/* Generated by nested-frame-emit.factor. */"]
for name in ("caller", "callee", "map", "caller64", "caller128", "callee64", "callee96"):
    values = ",".join(f"0x{x:02x}" for x in
                      (directory / f"m88k-nested-{name}.bin").read_bytes())
    lines.append(f"static const unsigned char nested_{name}[] = {{{values}}};")
Path(sys.argv[2]).write_text("\n".join(lines) + "\n")

#!/usr/bin/env python3
"""Pack signal-emit.factor outputs for signal-probe.c."""
from pathlib import Path
import sys

directory = Path(sys.argv[1])
lines = ["/* Generated by signal-emit.factor. */"]
for name in ("resume", "map"):
    data = (directory / f"m88k-signal-{name}.bin").read_bytes()
    values = ",".join(f"0x{value:02x}" for value in data)
    lines.append(f"static const unsigned char signal_{name}[] = {{{values}}};")
Path(sys.argv[2]).write_text("\n".join(lines) + "\n")
